// UpdatePlanningGroup renames a planning group.
func UpdatePlanningGroup(model UpdatePlanningGroupModel) error {
	m := msql.Model(define.TablePlanningGroups, define.Postgres)
	exist, err := m.Field(`id`).Where2([][]string{
		{`admin_id`, cast.ToString(model.AdminId)},
		{`workspace_id`, model.WorkspaceId},
		{`id`, cast.ToString(model.GroupId)},
	}).Value(`id`)
	if err != nil {
		logs.Error("check planning group sql:%s, err:%s", m.GetLastSql(), err.Error())
		return err
	}
	if len(exist) == 0 {
		return ErrPlanningGroupNotFound
	}
	updateM := msql.Model(define.TablePlanningGroups, define.Postgres)
	if _, err := updateM.Where2([][]string{
		{`admin_id`, cast.ToString(model.AdminId)},
		{`workspace_id`, model.WorkspaceId},
		{`id`, cast.ToString(model.GroupId)},
	}).Update(msql.Datas{
		`name`:       model.Name,
		`updated_at`: tool.Time2Int(),
	}); err != nil {
		logs.Error("update planning group sql:%s, err:%s", updateM.GetLastSql(), err.Error())
		return err
	}
	return nil
}

// DeletePlanningGroup deletes a planning group and all its planning data; at least one group must remain.
func DeletePlanningGroup(model DeletePlanningGroupModel) error {
	tx, err := msql.Begin(define.Postgres)
	if err != nil {
		logs.Error("begin delete planning group transaction failed, err:%s", err.Error())
		return err
	}
	defer func() { _ = tx.Rollback() }()

	groupRows, err := msql.RawValues(define.Postgres, `SELECT id FROM planning_groups
		WHERE admin_id = $1 AND workspace_id = $2 AND deleted_at = 0 FOR UPDATE`, tx, model.AdminId, cast.ToInt(model.WorkspaceId))
	if err != nil {
		logs.Error("lock planning groups failed, err:%s", err.Error())
		return err
	}
	found := false
	for _, row := range groupRows {
		if cast.ToInt(row[`id`]) == model.GroupId {
			found = true
			break
		}
	}
	if !found {
		return ErrPlanningGroupNotFound
	}
	if len(groupRows) <= 1 {
		return ErrPlanningGroupLastOne
	}

	// Empty-title rows follow the single-row delete path: purge them physically instead of
	// filling the recycle bin with unidentifiable entries. This must run before the soft delete
	// below, otherwise they are already marked deleted and can no longer be selected here.
	emptyRows, err := msql.RawValues(define.Postgres, `SELECT id FROM requirements
		WHERE admin_id = $1 AND workspace_id = $2 AND type = $3 AND group_id = $4
		  AND deleted_at = 0 AND TRIM(title) = ''`,
		tx, model.AdminId, cast.ToInt(model.WorkspaceId), define.TypeKeyPlanning, model.GroupId)
	if err != nil {
		logs.Error("query empty-title plannings failed, err:%s", err.Error())
		return err
	}
	emptyIds := make([]int, 0, len(emptyRows))
	for _, row := range emptyRows {
		emptyIds = append(emptyIds, cast.ToInt(row[`id`]))
	}
	if err = purgePlanningRows(tx, model.AdminId, model.WorkspaceId, emptyIds); err != nil {
		return err
	}

	// Named rows go to the recycle bin, keeping relations and custom field values for restore;
	// the group itself is hidden last.
	now := int64(tool.Time2Int())
	if _, err = msql.RawExec(define.Postgres, `UPDATE requirements SET deleted_at = $1, deleted_by = $2
		WHERE admin_id = $3 AND workspace_id = $4 AND type = $5 AND group_id = $6 AND deleted_at = 0`,
		tx, now, model.UserId, model.AdminId, cast.ToInt(model.WorkspaceId), define.TypeKeyPlanning, model.GroupId); err != nil {
		logs.Error("soft delete planning rows failed, err:%s", err.Error())
		return err
	}
	if _, err = msql.RawExec(define.Postgres, `UPDATE planning_groups SET deleted_at = $1, updated_at = $1
		WHERE admin_id = $2 AND workspace_id = $3 AND id = $4`,
		tx, now, model.AdminId, cast.ToInt(model.WorkspaceId), model.GroupId); err != nil {
		logs.Error("soft delete planning group failed, err:%s", err.Error())
		return err
	}
	if err = tx.Commit(); err != nil {
		logs.Error("commit delete planning group transaction failed, err:%s", err.Error())
	}
	return err
}

// seedPlanningDefaultGroup seeds a default group for a new workspace; the name stores an i18n key.
func seedPlanningDefaultGroup(adminId int, wsId string, now int) error {
	m := msql.Model(define.TablePlanningGroups, define.Postgres)
	exist, err := m.Field(`id`).Where2([][]string{
		{`admin_id`, cast.ToString(adminId)},
		{`workspace_id`, wsId},
		{`deleted_at`, `0`},
	}).Value(`id`)
	if err != nil {
		logs.Error("check planning default group sql:%s, err:%s", m.GetLastSql(), err.Error())
		return err
	}
	if len(exist) > 0 {
		return nil
	}
	insertM := msql.Model(define.TablePlanningGroups, define.Postgres)
	if _, err := insertM.Insert(msql.Datas{
		`admin_id`:     adminId,
		`workspace_id`: wsId,
		`name`:         lib_i18n.WrapKey(`planning_group_default`),
		`created_at`:   now,
		`updated_at`:   now,
	}); err != nil {
		logs.Error("seed planning default group sql:%s, err:%s", insertM.GetLastSql(), err.Error())
		return err
	}
	logs.Info("workspace [%s] planning default group seeded", wsId)
	return nil
}

