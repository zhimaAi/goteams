// toPlanningGroupModel converts a group data row into a business model.
func toPlanningGroupModel(row msql.Params, lang string) (PlanningGroupModel, error) {
	id, err := strconv.Atoi(row[`id`])
	if err != nil {
		return PlanningGroupModel{}, fmt.Errorf(`parse planning group id: %w`, err)
	}
	createdAt, err := strconv.ParseInt(row[`created_at`], 10, 64)
	if err != nil {
		return PlanningGroupModel{}, fmt.Errorf(`parse planning group created_at: %w`, err)
	}
	updatedAt, err := strconv.ParseInt(row[`updated_at`], 10, 64)
	if err != nil {
		return PlanningGroupModel{}, fmt.Errorf(`parse planning group updated_at: %w`, err)
	}
	return PlanningGroupModel{
		Id:        id,
		Name:      lib_i18n.ShowStored(lang, row[`name`]),
		CreatedAt: createdAt,
		UpdatedAt: updatedAt,
	}, nil
}

// ListPlanningGroups returns the planning groups under the workspace (in creation order).
func ListPlanningGroups(model ListPlanningGroupsModel) (ListPlanningGroupsModel, error) {
	m := msql.Model(define.TablePlanningGroups, define.Postgres)
	rows, err := m.Field(`id, name, created_at, updated_at`).Where2([][]string{
		{`admin_id`, cast.ToString(model.AdminId)},
		{`workspace_id`, model.WorkspaceId},
		{`deleted_at`, `0`},
	}).Order(`id asc`).Select()
	if err != nil {
		logs.Error("list planning groups sql:%s, err:%s", m.GetLastSql(), err.Error())
		return ListPlanningGroupsModel{}, err
	}
	items := make([]PlanningGroupModel, 0, len(rows))
	for _, row := range rows {
		item, convErr := toPlanningGroupModel(row, model.Lang)
		if convErr != nil {
			logs.Error("convert planning group row failed, err:%s", convErr.Error())
			return ListPlanningGroupsModel{}, convErr
		}
		items = append(items, item)
	}
	model.Items = items
	return model, nil
}

