package validate

import (
	"errors"
	"strings"

	"goteams/internal/app/goteams/define"
)

// ErrOauthInvalid means the third-party login request parameters are invalid.
var ErrOauthInvalid = errors.New("invalid oauth request")

// ValidateOauthProvider validates the third-party provider key.
func ValidateOauthProvider(provider string) error {
	if provider != define.OauthProviderDingtalk && provider != define.OauthProviderFeishu {
		return ErrOauthInvalid
	}
	return nil
}

// ValidateOauthScene validates the scan-code scene.
func ValidateOauthScene(scene string) error {
	if scene != define.OauthSceneLogin && scene != define.OauthSceneBind {
		return ErrOauthInvalid
	}
	return nil
}

// ValidateOauthTicket validates the shape of a one-time ticket.
// Tickets are hex strings generated by the backend; anything else cannot come from us.
func ValidateOauthTicket(ticket string) error {
	trimmed := strings.TrimSpace(ticket)
	if len(trimmed) < 32 || len(trimmed) > 128 {
		return ErrOauthInvalid
	}
	for _, char := range trimmed {
		isDigit := char >= '0' && char <= '9'
		isLowerHex := char >= 'a' && char <= 'f'
		if !isDigit && !isLowerHex {
			return ErrOauthInvalid
		}
	}
	return nil
}
